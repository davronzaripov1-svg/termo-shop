export async function getPage(slug: string) {
  const page = await prisma.page.findUnique({ where: { slug } })
  if (page) return page.isActive ? { ...page, isDefault: false } : null
  const fallback = DEFAULT_PAGES[slug]
  return fallback
    ? { slug, ...fallback, metaTitle: null, metaDescription: null, isActive: true, isDefault: true }
    : null
}
